"""
Ubuntu Netplan Static IP Configuration Manager
Provides safe Netplan generation, pre-syntax checking, and auto-rollback to protect SSH sessions.
"""

import os
import shutil
import socket
import subprocess
import time
from pathlib import Path
from typing import Dict, Any, List, Optional


def probe_network_interfaces() -> Dict[str, Any]:
    """
    Detects network interfaces, active LAN IP, default gateway, and nameservers.
    Inspects Linux /sys/class/net, /proc/net/route, and resolv.conf.
    """
    interfaces = []
    default_ip = "127.0.0.1"
    active_nic = "eth0"
    gateway = "192.168.1.1"
    dns_servers = ["1.1.1.1", "8.8.8.8"]

    # 1. Detect Primary Outbound IP using UDP socket probe (no packets actually sent)
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("1.1.1.1", 80))
            default_ip = s.getsockname()[0]
    except Exception:
        pass

    # 2. Inspect Linux /sys/class/net and /proc/net/route
    sys_net = Path("/sys/class/net")
    if sys_net.exists():
        for iface_path in sys_net.iterdir():
            iface_name = iface_path.name
            if iface_name == "lo" or iface_name.startswith(("docker", "veth", "br-", "tailscale")):
                continue

            # Check link speed
            speed_file = iface_path / "speed"
            speed_mbps = 1000
            if speed_file.exists():
                try:
                    val = int(speed_file.read_text().strip())
                    if val > 0:
                        speed_mbps = val
                except Exception:
                    pass

            # Check operstate
            operstate_file = iface_path / "operstate"
            is_up = False
            if operstate_file.exists():
                try:
                    is_up = (operstate_file.read_text().strip() == "up")
                except Exception:
                    pass

            interfaces.append({
                "name": iface_name,
                "is_up": is_up,
                "speed_mbps": speed_mbps,
            })

    # Linux Default Gateway detection via /proc/net/route
    route_file = Path("/proc/net/route")
    if route_file.exists():
        try:
            with open(route_file, "r") as f:
                for line in f:
                    fields = line.strip().split()
                    if len(fields) >= 3 and fields[1] == "00000000":
                        active_nic = fields[0]
                        # Hex IP to dotted-quad
                        hex_gw = fields[2]
                        if len(hex_gw) == 8:
                            b = [int(hex_gw[i:i+2], 16) for i in (6, 4, 2, 0)]
                            gateway = ".".join(map(str, b))
                        break
        except Exception:
            pass

    # Linux DNS detection via /etc/resolv.conf
    resolv_file = Path("/etc/resolv.conf")
    if resolv_file.exists():
        try:
            detected_dns = []
            with open(resolv_file, "r") as f:
                for line in f:
                    if line.startswith("nameserver"):
                        parts = line.strip().split()
                        if len(parts) >= 2 and not parts[1].startswith("127.0.0."):
                            detected_dns.append(parts[1])
            if detected_dns:
                dns_servers = detected_dns[:2]
        except Exception:
            pass

    # Fallback if no interfaces discovered (e.g., Windows dev environment)
    if not interfaces:
        interfaces.append({
            "name": "eth0",
            "is_up": True,
            "speed_mbps": 1000,
        })
        active_nic = "eth0"

    return {
        "active_nic": active_nic,
        "current_ip": default_ip,
        "default_gateway": gateway,
        "dns_servers": dns_servers,
        "interfaces": interfaces,
    }


def generate_netplan_yaml(
    interface: str,
    ip_with_cidr: str,
    gateway: str,
    dns_servers: List[str]
) -> str:
    """Generates standard, syntactically clean Netplan v2 YAML configuration"""
    dns_formatted = ", ".join(f'"{d.strip()}"' for d in dns_servers if d.strip())
    yaml_content = f"""# Generated by Homelab Blueprint Setup Wizard
network:
  version: 2
  renderer: networkd
  ethernets:
    {interface}:
      dhcp4: false
      addresses:
        - {ip_with_cidr}
      routes:
        - to: default
          via: {gateway}
      nameservers:
        addresses: [{dns_formatted}]
"""
    return yaml_content


def backup_netplan_configs(netplan_dir: str = "/etc/netplan") -> Optional[str]:
    """Creates a timestamped backup directory of all existing Netplan files"""
    p = Path(netplan_dir)
    if not p.exists():
        return None

    timestamp = int(time.time())
    backup_dir = p / f"backup_{timestamp}"
    backup_dir.mkdir(parents=True, exist_ok=True)

    copied = 0
    for item in p.glob("*.yaml"):
        if item.is_file():
            shutil.copy2(item, backup_dir / item.name)
            copied += 1

    return str(backup_dir) if copied > 0 else None


def safe_apply_netplan(
    interface: str,
    ip_address: str,
    cidr: int = 24,
    gateway: str = "192.168.1.1",
    dns_servers: Optional[List[str]] = None,
    timeout_sec: int = 45,
    netplan_dir: str = "/etc/netplan",
    target_filename: str = "99-homelab-blueprint.yaml"
) -> Dict[str, Any]:
    """
    Safely generates and applies Netplan configuration with auto-rollback.
    Protects SSH sessions from getting severed by network misconfiguration.
    """
    if dns_servers is None:
        dns_servers = ["1.1.1.1", "8.8.8.8"]

    ip_with_cidr = f"{ip_address}/{cidr}" if "/" not in ip_address else ip_address
    yaml_content = generate_netplan_yaml(interface, ip_with_cidr, gateway, dns_servers)

    p_dir = Path(netplan_dir)

    # Dev/Non-Linux mock execution
    if os.name == "nt" or not p_dir.exists():
        return {
            "success": True,
            "mode": "simulation",
            "applied_yaml": yaml_content,
            "ip": ip_with_cidr,
            "message": "Netplan simulation verified (non-Linux environment).",
        }

    # 1. Create safety backup
    backup_path = backup_netplan_configs(netplan_dir)

    # 2. Write proposed config to target file
    config_file = p_dir / target_filename
    config_file.write_text(yaml_content)
    os.chmod(str(config_file), 0o600)

    # 3. Syntax validation via 'netplan generate'
    gen_cmd = subprocess.run(
        ["netplan", "generate"],
        capture_output=True,
        text=True
    )
    if gen_cmd.returncode != 0:
        # Revert write immediately
        if config_file.exists():
            config_file.unlink()
        return {
            "success": False,
            "stage": "syntax_validation",
            "error": gen_cmd.stderr or gen_cmd.stdout,
            "message": "Netplan syntax check failed. Reverted to previous network configuration.",
        }

    # 4. Apply via 'netplan try' with auto-rollback
    try:
        # netplan try --timeout <sec> reverts automatically if connection drops
        try_cmd = subprocess.run(
            ["netplan", "try", f"--timeout={timeout_sec}"],
            input="\n",  # Accept immediately if healthy
            capture_output=True,
            text=True,
            timeout=timeout_sec + 5
        )

        if try_cmd.returncode == 0:
            return {
                "success": True,
                "ip": ip_with_cidr,
                "interface": interface,
                "backup_dir": backup_path,
                "message": f"Static IP {ip_with_cidr} successfully applied via Netplan.",
            }
        else:
            return {
                "success": False,
                "stage": "try_apply",
                "error": try_cmd.stderr or try_cmd.stdout,
                "message": "Netplan rejected the configuration and automatically rolled back.",
            }
    except subprocess.TimeoutExpired:
        # Revert from backup if timed out
        if backup_path and Path(backup_path).exists():
            for backup_file in Path(backup_path).glob("*.yaml"):
                shutil.copy2(backup_file, p_dir / backup_file.name)
            subprocess.run(["netplan", "apply"], capture_output=True)

        return {
            "success": False,
            "stage": "timeout_reverted",
            "error": "Netplan apply timed out. Automatically reverted to backup network configuration.",
        }
    except Exception as e:
        return {
            "success": False,
            "stage": "exception",
            "error": str(e),
        }
